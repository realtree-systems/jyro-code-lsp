// Writes the standard library table the language service reads: each function
// StdlibRegistry.GetAll() gives, with its parameters, arity, return type and
// effect from the registry, and its documentation from Jyro.Stdlib.xml.
//
// Usage: StdlibGen <output .ts file> <source description>

using System.Reflection;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Xml.Linq;
using RealTree.Jyro;

if (args.Length != 2)
{
    Console.Error.WriteLine("Usage: StdlibGen <output .ts file> <source description>");
    return 2;
}

var outputPath = args[0];
var source = args[1];

var stdlibAssembly = typeof(StdlibRegistry).Assembly;
var xmlPath = Path.ChangeExtension(stdlibAssembly.Location, ".xml");
if (!File.Exists(xmlPath))
{
    Console.Error.WriteLine($"No documentation file at {xmlPath}: Jyro 15c73c1 or later builds one.");
    return 1;
}

var members = XDocument.Load(xmlPath).Descendants("member")
    .ToDictionary(m => (string)m.Attribute("name")!, m => m);

var functions = new JsonArray();
var problems = new List<string>();

foreach (var f in StdlibRegistry.GetAll())
{
    // The member of a function is its class's: "T:" and the full name, with
    // the '+' of a nested type written as '.'
    var type = f.GetType();
    var id = "T:" + type.FullName!.Replace('+', '.');
    if (!members.TryGetValue(id, out var member))
    {
        problems.Add($"{f.Name}: no member {id}");
        continue;
    }

    var args_ = member.Elements("arg").ToList();
    var parameters = f.Signature.Parameters;
    if (args_.Count != parameters.Count
        || args_.Where((a, i) => (string)a.Attribute("name")! != parameters[i].Name).Any())
    {
        problems.Add($"{f.Name}: the <arg> names do not match the signature's parameters");
        continue;
    }

    var parameterNodes = new JsonArray();
    for (var i = 0; i < parameters.Count; i++)
    {
        var p = parameters[i];
        var node = new JsonObject
        {
            ["name"] = p.Name,
            ["type"] = TypeName(p.Type),
        };
        if (p.IsOptional) node["optional"] = true;
        node["description"] = Markdown(args_[i]);
        parameterNodes.Add(node);
    }

    var entry = new JsonObject
    {
        ["name"] = f.Name,
        ["category"] = Category(type),
        ["parameters"] = parameterNodes,
        ["returnType"] = TypeName(f.Signature.ReturnType),
        ["description"] = Markdown(member.Element("summary")!),
        ["returns"] = Markdown(member.Element("returns")!),
        ["minArgs"] = f.Signature.MinArgs,
        ["maxArgs"] = f.Signature.MaxArgs,
        ["effect"] = f.Effect.ToString(),
    };
    if (member.Element("remarks") is { } remarks) entry["remarks"] = Markdown(remarks);
    var examples = member.Elements("example").Select(e => (JsonNode?)Markdown(e)).ToArray();
    if (examples.Length > 0) entry["exampleText"] = new JsonArray(examples);
    functions.Add(entry);
}

if (problems.Count > 0)
{
    foreach (var p in problems) Console.Error.WriteLine(p);
    return 1;
}

var json = functions.ToJsonString(new JsonSerializerOptions
{
    WriteIndented = true,
    Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
});

var ts = new StringBuilder()
    .Append("// Generated by tools/stdlib-gen from ").Append(source).Append('\n')
    .Append("// Do not edit: run `npm run generate:stdlib` to regenerate it.\n")
    .Append('\n')
    .Append("import type { FunctionSignature } from './stdlib';\n")
    .Append('\n')
    .Append("export const GENERATED_STDLIB_FUNCTIONS: FunctionSignature[] = ")
    .Append(json.Replace("\r\n", "\n").Replace("  ", "    "))
    .Append(";\n")
    .ToString();

File.WriteAllText(outputPath, ts, new UTF8Encoding(false));
Console.WriteLine($"Wrote {functions.Count} functions to {outputPath}");
return 0;

// "string", "number" and so on, as Jyro's type names are written
static string TypeName(ParameterType t) => t.ToString().ToLowerInvariant();

// StringFunctions -> String
static string Category(Type t)
{
    var name = t.DeclaringType?.Name ?? t.Name;
    return name.EndsWith("Functions", StringComparison.Ordinal) ? name[..^"Functions".Length] : name;
}

// The text of a documentation element as Markdown: <c> becomes inline code,
// and the line breaks and indentation of the XML become single spaces
static string Markdown(XElement e)
{
    var sb = new StringBuilder();
    foreach (var node in e.Nodes())
    {
        switch (node)
        {
            case XText text:
                sb.Append(text.Value);
                break;
            case XElement { Name.LocalName: "c" } code:
                sb.Append('`').Append(code.Value).Append('`');
                break;
            case XElement other:
                sb.Append(other.Value);
                break;
        }
    }
    return System.Text.RegularExpressions.Regex.Replace(sb.ToString(), @"\s+", " ").Trim();
}
